/* 按长度找档位；table 省略时为直线度/平面度的表 B1，定向公差传 ORIENTATION_TABLE（表 B3），档位划分相同 */
function findRange(length, table) {
  table = table || TOLERANCE_TABLE;
  for (const r of table) {
    if (length > r.min && length <= r.max) return r;
  }
  if (length === 0) return table[0];
  return null;
}

